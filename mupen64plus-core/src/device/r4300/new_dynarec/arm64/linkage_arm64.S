#if defined(__APPLE__)

/* Apple's arm64 clang assembler treats ';' as a comment delimiter,
 * not a statement separator, so a single-line cpp macro can't emit
 * the .globl/.private_extern/label triple. Use assembler-side macros
 * which support multi-line bodies natively. The cpp wrapper drops the
 * trailing ':' that GAS-style call sites add. */
.macro GLOBAL_FUNCTION_M name
.globl _\name
.private_extern _\name
_\name:
.endm

.macro LOCAL_FUNCTION_M name
.private_extern _\name
_\name:
.endm

/* The cpp macro forwards to the asm-side macro which emits the full
 * .globl / .private_extern / label sequence on separate lines.
 * Note: call sites must NOT end with ':' on Apple — the asm macro
 * provides the label colon. The Linux GAS branch also provides the
 * label, so both are consistent. */
#define GLOBAL_FUNCTION(name) GLOBAL_FUNCTION_M name
#define LOCAL_FUNCTION(name)  LOCAL_FUNCTION_M name

.macro GLOBAL_VARIABLE_M name
.globl _\name
.private_extern _\name
.endm
#define GLOBAL_VARIABLE(name, size_) GLOBAL_VARIABLE_M name

/* On Apple, all C symbols carry a leading underscore in Mach-O.
 * Internal symbols defined in this file use the L-label fallback
 * generated by GLOBAL_FUNCTION/LOCAL_FUNCTION above.
 * Pure external symbols are rewritten with the cpp defines below. */
#define get_addr               _get_addr
#define get_addr_ht            _get_addr_ht
#define new_recompile_block    _new_recompile_block
#define verify_dirty           _verify_dirty
#define cop1_unusable          _cop1_unusable
#define dynamic_linker         _dynamic_linker
#define dynamic_linker_ds      _dynamic_linker_ds
#define dynarec_gen_interrupt  _dynarec_gen_interrupt
#define SYSCALL_new            _SYSCALL_new
#define ERET_new               _ERET_new

#else

#define GLOBAL_FUNCTION(name)  \
    .globl name;               \
    .hidden name;              \
    .type name, %function;     \
    name:

#define LOCAL_FUNCTION(name)  \
    .hidden name;             \
    .type name, %function;    \
    name:

#define GLOBAL_VARIABLE(name, size_) \
    .global name;                    \
    .hidden name;                    \
    .type   name, %object;           \
    .size   name, size_

#endif

.macro movl Wn, imm
    movz    \Wn, (\imm >> 16) & 0xFFFF, lsl 16
    movk    \Wn,  \imm & 0xFFFF
.endm

#if defined(__APPLE__)
.macro ADRP_LO12 reg, sym
    adrp    \reg, _\sym@PAGE
    add     \reg, \reg, _\sym@PAGEOFF
.endm
#else
.macro ADRP_LO12 reg, sym
    adrp    \reg, \sym
    add     \reg, \reg, :lo12:\sym
.endm
#endif

